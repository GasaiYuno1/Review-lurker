def unusual(t: pd.DataFrame, E: np.ndarray) -> None:
    t0 = time.time()
    enc = get_embedder(MODEL)
    extra = UNUSUAL + ORDINARY
    Ex = enc.encode(extra).astype(np.float32)
    print(f"эмбеддинги подмешанных: {time.time() - t0:.0f} с", flush=True)
    texts = t["clean"].fillna("").astype(str).tolist() + extra
    kind = np.array(["тикет"] * len(t) + ["необычный"] * len(UNUSUAL) + ["обычный_контроль"] * len(ORDINARY))
    EE = np.vstack([E, Ex])
    res = cluster_embeddings(EE, texts, method="umap_hdbscan", outlier_threshold=-1.0)
    topics = assign_topics(EE, res.labels)
    one = np.zeros(len(EE), int)
    scores = {"knn в кластере": robust_z(knn_score(EE, topics), topics),
              "центр кластера": robust_z(centroid_score(EE, topics), topics),
              "knn без кластеров": robust_z(knn_score(EE, one), one)}
    # короткие тексты (< 4 слов: «см. предыдущий», «пишет нет сгинаа») необычной проблемы не описывают — вне ранжирования
    short = np.array([len(x.split()) < 4 for x in texts])
    s2 = scores["knn в кластере"].copy()
    s2[short] = -np.inf
    scores["knn в кластере, от 4 слов"] = s2
    scores["knn без кластеров, от 4 слов"] = unusual_scores(EE, texts)        # lurker.novelty — то же, что в run_comments.py
    rows = []
    for name, s in scores.items():
        for target in ("необычный", "обычный_контроль"):
            keep = (kind == "тикет") | (kind == target)
            m = ranking_metrics(np.nan_to_num(s[keep], neginf=-1e6), kind[keep] == target, ks=(20, 50, 100))
            rows.append({"метод": name, "позитив": target, "n_pos": int((kind == target).sum()),
                         "доля": round(float((kind[keep] == target).mean()), 4), **{k: round(v, 3) for k, v in m.items()},
                         "помечено z≥2.5, %": round(100 * float((s[keep] >= 2.5).mean()), 1),
                         "доля позитива среди z≥2.5": round(float((kind[keep][s[keep] >= 2.5] == target).mean()), 3)})
    out = pd.DataFrame(rows)
    out.to_csv(RESULTS / "novelty_unusual.csv", index=False)
    print(out.to_string(index=False), flush=True)
    s = scores["knn без кластеров, от 4 слов"]
    o = np.argsort(-s)[:40]
    top = pd.DataFrame({"rank": range(1, 41), "z": np.round(s[o], 2), "kind": kind[o],
                        "label": [t["label"].iloc[i] if i < len(t) else "" for i in o], "text": [texts[i][:200] for i in o]})
    top.to_csv(RESULTS / "novelty_unusual_top.csv", index=False)
    print(top.to_string(index=False), flush=True)


def emerging(t: pd.DataFrame, E: np.ndarray) -> None:
    lab = pd.read_csv(ROOT / "data" / "test" / "tickets_labels.csv")[["ID", "trend"]]
    lab["id"] = "t-" + lab["ID"].astype(str)
    t = t.merge(lab[["id", "trend"]], on="id", how="left")
    t["date"] = pd.to_datetime(t["date"])
    month = t["date"].dt.to_period("M")
    first_seen = t.groupby("label")["date"].min()
    groups_all = emerging_groups(E, t["date"])
    rows = []
    for m, cur, new in novel_by_period(E, t["date"]):
        groups = []
        for _, g in groups_all[groups_all.period == str(m)].iterrows():
            idx = np.array(g.members)
            vc = t["label"].iloc[idx].value_counts()
            is_new = first_seen[vc.index[0]] >= m.start_time               # тема действительно впервые в этом месяце
            groups.append((len(idx), vc.index[0], round(vc.iloc[0] / len(idx), 2), bool(is_new),
                           " | ".join(t["clean"].iloc[idx[:3]].str[:80])))
        truly_new = t["label"][(month == m)].map(lambda x: first_seen[x] >= m.start_time)
        rows.append({"месяц": str(m), "тикетов": len(cur), "новизна выше порога": len(new),
                     "тикетов новых тем в месяце": int(truly_new.sum()),
                     "из них отмечены новизной": int(np.isin(cur[truly_new.to_numpy()], new).sum()),
                     "групп-кандидатов": len(groups),
                     "из них новая тема": sum(g[3] for g in groups),
                     "группы": "; ".join(f"{g[0]} шт · {g[1]} {g[2]:.0%}{' · НОВАЯ' if g[3] else ''}" for g in groups),
                     "примеры": " || ".join(g[4] for g in groups)})
    out = pd.DataFrame(rows)
    out.to_csv(RESULTS / "novelty_emerging.csv", index=False)
    print(out.drop(columns=["примеры"]).to_string(index=False), flush=True)


def main() -> int:
    t = pd.read_parquet(DATA / "comments" / "tickets.parquet")
    E = np.load(emb_path("tickets", "clean", MODEL)).astype(np.float32)
    step = sys.argv[1] if len(sys.argv) > 1 else "all"
    if step in ("all", "emerging"):
        emerging(t, E)
    if step in ("all", "unusual"):
        unusual(t, E)
    return 0


if __name__ == "__main__":
    sys.exit(main())
