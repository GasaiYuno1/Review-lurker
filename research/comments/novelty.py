"""Задача 1, два вопроса заказчика из ТЗ, которые кластеры сами по себе не закрывают:
  «какие необычные проблемы встречаются в комментариях» и «какие темы появляются».

A. Необычные комментарии (метод из задачи 2: новизна внутри темы). В очищенные тикеты подмешаны 50 написанных вручную
   НЕОБЫЧНЫХ, но правдоподобных обращений (роутер искрит, домофон сам открывает дверь ночью, в квитанции чужая фамилия…)
   и, для контроля, 50 написанных тем же автором и в том же стиле ОБЫЧНЫХ обращений по существующим темам. Если метод
   поднимает и контрольные, он ловит «чужой стиль», а не необычный смысл. Оценка — кластеры как в эксперименте
   (USER-bge-m3, UMAP + HDBSCAN), внутри кластера среднее сходство с 10 ближайшими соседями (lurker.anomaly.knn_score),
   робастный z по кластеру; для сравнения — то же без кластеров (по всему корпусу) и расстояние до центра кластера;
   варианты «от 4 слов» не ранжируют короткие тексты (опечатки, «см. предыдущий»). Топ-40 — по лучшему варианту.
B. Новые темы по месяцам. Для каждого месяца M: эталон — все тикеты до M; у каждого тикета M новизна = 1 − среднее
   сходство с 5 ближайшими тикетами эталона; «новые» — выше 99-го процентиля той же величины внутри эталона; новые
   тикеты группируются (агломеративная, косинус); группа ≥ 5 тикетов — кандидат в новую тему. В тикеты при генерации
   заложена одна новая тема (с 10 августа, «приложение не открывается после обновления»); остальные месяцы показывают,
   сколько ложных «новых тем» даёт метод.
python3 research/comments/novelty.py → research/results/novelty_unusual.csv, novelty_unusual_top.csv, novelty_emerging.csv
"""
