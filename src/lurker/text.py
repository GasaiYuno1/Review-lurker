@functools.lru_cache(maxsize=200_000)
def lemma(word: str) -> str:
    if _MORPH is None:
        return word
    return _MORPH.parse(word)[0].normal_form


def tokens(text: str) -> list[str]:
    return [t.lower().replace("ё", "е") for t in TOKEN_RE.findall(text)]


def lemmas(text: str, stop: bool = True, min_len: int = 2) -> list[str]:
    out = []
    for t in tokens(text):
        if len(t) < min_len or t.isdigit():
            continue
        l = lemma(t).replace("ё", "е")
        if stop and (l in STOPWORDS or l in DOMAIN_STOP or t in STOPWORDS):
            continue
        out.append(l)
    return out


def lemmatize(text: str) -> str:
    """Строка лемм — вход для TF-IDF / CountVectorizer."""
    return " ".join(lemmas(text))


def analyzer(text: str) -> list[str]:
    """Для sklearn (analyzer=...): леммы + биграммы лемм."""
    ls = lemmas(text)
    return ls + [f"{a} {b}" for a, b in zip(ls, ls[1:])]


def ngrams(items: Iterable[str], n: int) -> list[str]:
    items = list(items)
    return [" ".join(items[i:i + n]) for i in range(len(items) - n + 1)]
