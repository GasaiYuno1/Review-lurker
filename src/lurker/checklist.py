"""Проверка звонков LLM по чек-листу контролёра: на звонок — метка, итог для клиента и признак повторного обращения.

На прод-данных заказчика (research/REPORT.md) это единственный способ, который ловит конкретные нарушения: из 54
подложенных в настоящий поток Claude Haiku находит 45–46 при 1 ложной тревоге на 54 обычных; поиск по новизне — 4.
Модель задаётся конфигом LLM (configs/*.yaml): облачная (configs/haiku.yaml) или локальная (Qwen3-8B и крупнее; 4B
не годится). Звонок отправляется целиком с ролями ОП/КЛ; ответ — JSON.

На всём месяце звонков заказчика (42 600, Haiku) пометка A стоит у 1.4% звонков, но подтверждается в основном вид
«грубость» (note_kind): 6 из 20 и ещё 4 спорных; «неверная информация» и «отказ помогать» без справочника правил
компании почти всегда ложные — модель принимает регламентные отказы за ошибки. Поэтому контролю — сначала «грубость».

Метки (если подходят несколько — первая по списку):
  A — нарушение: грубость или хамство оператора, бред/явно неверная информация, личный разговор не по работе, отказ помогать;
  R — роли перепутаны;  T — не разговор (автоответчик, обрыв);
  S — показать контролю, но не нарушение (конфликт при корректном операторе, звонит не абонент, нестандартная просьба…);
  N — обычный звонок.
Итог: D — решено в разговоре, P — передано дальше (заявка, выезд, перевод, перезвон), X — помочь не смогли, U — неясно.
Повтор: 1, если клиент говорит, что обращается по этому вопросу не впервые.
"""
from __future__ import annotations

import re
from typing import Optional, Sequence

from .llm import parse_json

SYSTEM = "Ты — контролёр качества колл-центра. Отвечай только JSON."
TASK = """Ниже звонок в поддержку: автоматическая расшифровка речи (нижний регистр, без пунктуации, слова искажены и
обрезаны — это нормально и само по себе не нарушение). «ОП:» — оператор, «КЛ:» — клиент; метки расставлены
автоматически и иногда перепутаны.{topic}

{dialog}

Оцени звонок:
1. label — одна буква:
- A — нарушение, которое контролёр обязан увидеть: грубость или хамство оператора, бред/явно неверная информация от
  оператора, разговор оператора не по теме работы (личное), отказ помогать.
- R — роли перепутаны: под «ОП:» явно говорит клиент.
- T — не разговор: автоответчик, голосовой ассистент, обрыв без содержания.
- S — необычный звонок, который стоит показать контролю, но не нарушение: конфликт (клиент резок, оператор корректен),
  оператор перезвонил исправить свою ошибку, звонит не абонент, оператор долго болтает не по делу, нестандартная
  просьба, подозрение на мошенников.
- N — обычный звонок.
Если подходят несколько — первая по списку A, R, T, S, N. Не ставь A без явного признака в тексте; искажения
распознавания (например, «для» → «бля») — не грубость. Брань клиента — не нарушение оператора.
2. outcome — итог для клиента: D — решено в разговоре; P — передано дальше (заявка, выезд инженера, перевод в другой
отдел, обещан перезвон); X — помочь не смогли (услуги нет, нельзя по правилам, нужно в офис или к другой компании);
U — неясно (обрыв, не разговор).
3. repeat — 1, если клиент говорит, что обращается по этому вопросу не впервые («уже звонил», «опять», «мастер не
пришёл»), иначе 0.
4. note — для label кроме N одна короткая фраза, почему (без имён, адресов и телефонов); для N — пустая строка.

Ответ — JSON: {{"label": "...", "outcome": "...", "repeat": 0, "note": "..."}}"""

LABELS, OUTCOMES = "ARTSN", "DPXU"
NOTE_KINDS = [("грубость", r"груб|хам|оскорб|раздраж|повыш|пренебр|неуваж|сарказ|издев|перебива"),
              ("неверная информация", r"невер|ошиб|противореч|неправ|дезинф|бред|путан|неточн"),
              ("отказ помогать", r"отказ|не помог|отказыв|отфутбол|не стал"),
              ("личное", r"личн|не по теме|не по работе|посторон")]


def note_kind(note) -> str:
    """Пояснение модели к пометке A → вид нарушения (первый подошедший из NOTE_KINDS) или «прочее»."""
    n = str(note or "").lower()
    return next((k for k, pat in NOTE_KINDS if re.search(pat, n)), "прочее")


def format_dialog(turns: Sequence[tuple[str, str]], max_chars: int = 1500, max_total: int = 40_000) -> str:
    """[(op|cl, текст)] → строки «ОП: …» / «КЛ: …»; длинные реплики и звонки обрезаются."""
    lines = [("ОП: " if s == "op" else "КЛ: ") + " ".join(str(x).split())[:max_chars] for s, x in turns]
    text = "\n".join(lines)
    return text if len(text) <= max_total else text[:max_total] + "\n…"


def parse_answer(raw) -> dict:
    """Ответ модели → {label, outcome, repeat, note}; непонятное — label «?»."""
    d = raw if isinstance(raw, dict) else {}
    if not d and isinstance(raw, str):
        try:
            d = parse_json(raw) or {}
        except Exception:
            m = re.search(r"\b([ARTSN])\b", raw)
            d = {"label": m.group(1)} if m else {}
    lab = str(d.get("label", "")).strip().upper()[:1]
    out = str(d.get("outcome", "")).strip().upper()[:1]
    try:
        rep = int(str(d.get("repeat", 0)).strip() or 0)
    except ValueError:
        rep = 0
    return {"label": lab if lab in LABELS else "?", "outcome": out if out in OUTCOMES else "U",
            "repeat": 1 if rep else 0, "note": str(d.get("note", "") or "").strip()[:300]}


def check_call(turns: Sequence[tuple[str, str]], llm, topic: Optional[str] = None) -> dict:
    """Один звонок → {label, outcome, repeat, note}. llm — LLMClient или FakeLLM."""
    prompt = TASK.format(topic=f"\nТема из разметки: {topic}." if topic else "", dialog=format_dialog(turns))
    msgs = [{"role": "system", "content": SYSTEM}, {"role": "user", "content": prompt}]
    try:
        return parse_answer(llm.chat_json(msgs))
    except Exception:
        return parse_answer(llm.chat(msgs))
