# ============================================================ тренды

Trend = Callable[[date], float]


def spike(peak: date, width_days: float, height: float) -> Trend:
    """Всплеск: множитель 1 + height·exp(−((d−peak)/width)²)."""
    def f(d: date) -> float:
        x = (d - peak).days / width_days
        return 1.0 + height * math.exp(-x * x)
    return f


def ramp(start: date, end: date, to: float) -> Trend:
    """Линейный рост множителя с 1 до `to` между start и end, дальше держится."""
    def f(d: date) -> float:
        if d <= start:
            return 1.0
        if d >= end:
            return to
        return 1.0 + (to - 1.0) * (d - start).days / (end - start).days
    return f


def appear(start: date) -> Trend:
    """Тема появляется только с даты start."""
    return lambda d: 1.0 if d >= start else 0.0


def by_month(mult: dict) -> Trend:
    return lambda d: mult.get(d.month, 1.0)


