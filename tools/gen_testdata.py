def abbreviate(rng: random.Random, s: str) -> str:
    for pat, rep, p in ABBR:
        if rng.random() < p:
            s = re.sub(pat, rep, s)
    return s


def typo(rng: random.Random, s: str, n: Optional[int] = None) -> str:
    words = s.split(" ")
    idxs = [i for i, w in enumerate(words) if len(w) > 4 and w.isalpha()]
    if not idxs:
        return s
    n = n or rng.choice([1, 1, 2])
    for i in rng.sample(idxs, min(len(idxs), n)):
        w = words[i]
        k = rng.randrange(1, len(w) - 1)
        op = rng.random()
        if op < 0.4:
            w = w[:k] + w[k + 1] + w[k] + w[k + 2:]
        elif op < 0.7:
            w = w[:k] + w[k + 1:]
        else:
            w = w[:k] + w[k] + w[k:]
        words[i] = w
    return " ".join(words)


def cap(s: str) -> str:
    return s[:1].upper() + s[1:] if s else s


def sep(rng: random.Random) -> str:
    return rng.choice([", ", ", ", ", ", "; ", ". ", " - ", " — "])


def apply_style(rng: random.Random, s: str, style: str) -> str:
    if style == "caps":
        return s.upper()
    if style == "nopunct":
        return re.sub(r"[,.;!—-]+", "", s).replace("  ", " ")
    if style == "terse":
        return re.split(r"[,;.] ", s)[0]
    if style == "verbose":
        return f"Абонент обратился с проблемой: {s}. Проведена консультация, информация зафиксирована."
    if style == "typos":
        return typo(rng, s, 2)
    return s


