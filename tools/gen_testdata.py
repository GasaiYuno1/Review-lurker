def generate(rows: int, seed: int, start: date, end: date) -> tuple[list[dict], list[dict]]:
    rng = random.Random(seed)
    days = [start + timedelta(i) for i in range((end - start).days + 1)]
    day_w = [WEEKDAY_W[d.weekday()] * sum(topic_weights(d)) for d in days]
    emp_w = {dept: [rng.uniform(0.5, 1.5) for _ in names] for dept, names in EMPLOYEES.items()}
    tw_cache: dict[date, list[float]] = {}

    items: list[tuple[datetime, dict, dict]] = []
    for _ in range(rows):
        d = rng.choices(days, day_w)[0]
        if d not in tw_cache:
            tw_cache[d] = topic_weights(d)
        t = rng.choices(TOPICS, tw_cache[d])[0]
        dept = pick_dept(rng, t)
        emp = rng.choices(EMPLOYEES[dept], emp_w[dept])[0]
        hour = rng.choices(list(HOUR_W), list(HOUR_W.values()))[0]
        ts = datetime(d.year, d.month, d.day, hour, rng.randrange(60))

        phrase, action = rng.choice(t.phrases), rng.choice(t.actions)
        text = RENDER[dept](rng, t, phrase, action, STYLE.get(emp, "normal"))
        topic2 = ""
        if rng.random() < 0.02:  # смешанное обращение: вторая тема
            t2 = rng.choice([x for x in TOPICS if x is not t])
            text += rng.choice([" также ", ", ещё ", ". Также спросил: ", "; плюс "]) + rng.choice(t2.phrases)
            topic2 = t2.key
        r = rng.random()
        if r < 0.01:
            text = ""
        elif r < 0.015:
            text = rng.choice(["-", "см. предыдущий", "."])

        service, sub = t.service, t.sub
        r = rng.random()
        if r < 0.04:
            service = rng.choice([s for s in SERVICES if s != t.service])
        elif r < 0.07:
            service = "Другое"
        if rng.random() < 0.15:
            sub = ""

        items.append((ts,
                      {"Отдел": dept, "Сотрудник": emp, "Сервис": service, "Подкатегория": sub, "Комментарий": text},
                      {"topic": t.key, "topic2": topic2, "sentiment": t.sentiment, "intent": t.intent,
                       "threat": int(t.threat), "trend": t.trend_name, "service_true": t.service}))

    # дубли: 1% — копия чужого комментария через 1–3 дня
    for _ in range(max(1, rows // 100)):
        ts, row, lab = rng.choice(items)
        items.append((ts + timedelta(days=rng.randrange(1, 4)), dict(row), dict(lab, dup=1)))

    items.sort(key=lambda x: x[0])
    out_rows, out_labels = [], []
    for i, (ts, row, lab) in enumerate(items):
        tid = 100000 + i
        out_rows.append({"ID": tid, "Дата создания": ts, **row})
        out_labels.append({"ID": tid, **{k: lab.get(k, "") for k in
                                         ("topic", "topic2", "sentiment", "intent", "threat", "trend", "service_true", "dup")}})
    return out_rows, out_labels


