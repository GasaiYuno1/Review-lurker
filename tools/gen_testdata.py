def write_csv(path: Path, rows: list[dict], sep_: str = ";", encoding: str = "utf-8-sig") -> None:
    with open(path, "w", newline="", encoding=encoding) as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]), delimiter=sep_)
        w.writeheader()
        for r in rows:
            r = dict(r)
            if isinstance(r.get("Дата создания"), datetime):
                r["Дата создания"] = r["Дата создания"].strftime("%Y-%m-%d %H:%M")
            w.writerow(r)


def write_xlsx(path: Path, rows: list[dict]) -> None:
    import pandas as pd
    df = pd.DataFrame(rows)
    with pd.ExcelWriter(path, engine="openpyxl", datetime_format="yyyy-mm-dd hh:mm") as xw:
        df.to_excel(xw, index=False, sheet_name="Тикеты")
        ws = xw.sheets["Тикеты"]
        for col, width in zip("ABCDEFG", (10, 18, 14, 16, 22, 20, 90)):
            ws.column_dimensions[col].width = width


def report(rows: list[dict], labels: list[dict]) -> str:
    from collections import Counter, defaultdict
    lines = [f"строк: {len(rows)}"]
    lines.append("по отделам: " + ", ".join(f"{k} {v}" for k, v in Counter(r["Отдел"] for r in rows).most_common()))
    months = sorted({r["Дата создания"].strftime("%Y-%m") for r in rows})
    per = defaultdict(Counter)
    for r, l in zip(rows, labels):
        per[l["topic"]][r["Дата создания"].strftime("%Y-%m")] += 1
    total = Counter(r["Дата создания"].strftime("%Y-%m") for r in rows)
    lines.append("\nтемы с трендом, число тикетов по месяцам:")
    lines.append(f"{'тема':45} " + " ".join(f"{m[2:]:>6}" for m in months))
    lines.append(f"{'всего':45} " + " ".join(f"{total[m]:6d}" for m in months))
    for t in TOPICS:
        if t.trend:
            lines.append(f"{t.key:45} " + " ".join(f"{per[t.key][m]:6d}" for m in months))
    lines.append("\nзаложенные тренды:")
    for k, v in TRENDS.items():
        lines.append(f"  {k}: {v}")
    return "\n".join(lines)


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--rows", type=int, default=3000)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--start", type=date.fromisoformat, default=date(2026, 1, 1))
    ap.add_argument("--end", type=date.fromisoformat, default=date(2026, 9, 7))
    ap.add_argument("--out", default="data/test/tickets", help="префикс выходных файлов")
    ap.add_argument("--no-xlsx", action="store_true")
    ap.add_argument("--quiet", action="store_true")
    a = ap.parse_args(argv)

    rows, labels = generate(a.rows, a.seed, a.start, a.end)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    write_csv(out.with_suffix(".csv"), rows)
    write_csv(out.with_name(out.name + "_labels.csv"), labels, sep_=",", encoding="utf-8")
    if not a.no_xlsx:
        write_xlsx(out.with_suffix(".xlsx"), rows)
    if not a.quiet:
        print(report(rows, labels))
        print(f"\n-> {out.with_suffix('.csv')}, {out.with_suffix('.xlsx') if not a.no_xlsx else '(без xlsx)'}, "
              f"{out.with_name(out.name + '_labels.csv')}")
    return 0


